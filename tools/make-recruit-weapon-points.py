# Measures where the Armoury sword and crossbow are held on the art team's recruit sheets
# (dist/assets/recruit-art-v2, drawn by cw-recruit-art-v2.mjs) and writes them to
# dist/cw-recruit-weapon-points.js for cw-weapon-art.js.
#
#   python3 tools/make-recruit-weapon-points.py dist
#
# The previous art had these points measured by hand (cw-weapon-grips.js and the
# fitted-equipment rig). For the new sheets they are measured from the art:
#   torso  every frame of the nine body rows: the middle of the coat (the coat mask).
#          cw-weapon-art.js holds the weapon just in front of and below this point, as it
#          did with the previous rig. For a body without a coat (the stone troll) the front
#          hand is measured instead (front-most pixel between 35% and 65% of the height)
#          and stored as the torso point that gives that hand.
#   grip   the six punch frames: the leading fist, i.e. the front-most opaque pixel between
#          20% and 60% of the figure's height (figures face left, so front-most = left-most).
# Coordinates are in atlas cell pixels, with the sheet's own foot point and visible height.
import json, os, sys
import numpy as np
from PIL import Image

DIST = sys.argv[1]
ART = os.path.join(DIST, 'assets/recruit-art-v2')
m = json.load(open(os.path.join(ART, 'manifest.json')))
W, H, COLS = m['cellWidth'], m['cellHeight'], m['cols']
out = {'cellWidth': W, 'cellHeight': H, 'footX': m['footX'], 'footY': m['footY'], 'bodies': {}}

def cell(px, i):
    r, c = divmod(i, COLS)
    return px[r * H:(r + 1) * H, c * W:(c + 1) * W]

for body, spec in m['bodies'].items():
    alpha = np.asarray(Image.open(os.path.join(ART, spec['files']['body'])).convert('RGBA'))[..., 3]
    coat_file = spec['files'].get('coat-mask')
    coat = np.asarray(Image.open(os.path.join(ART, coat_file)).convert('L')) if coat_file else None
    torso, grip = [], []
    for i in range(54):
        a = cell(alpha, i) > 64
        ys, xs = np.where(a)
        top, bottom = ys.min(), ys.max(); h = bottom - top + 1
        c = cell(coat, i) > 127 if coat is not None else None
        if c is not None and c.sum() > 20:
            cy, cx = np.where(c & a)
            torso.append([round(float(cx.mean()), 2), round(float(cy.mean()), 2)])
        else:
            # No coat (the stone troll): his body is too wide for a middle point, so find the
            # front hand (front-most opaque pixel at hand height) and store the torso point
            # that cw-weapon-art.js turns back into that hand (hand = torso + (-0.12, 0.15) x height).
            band = a.copy(); band[:top + int(h * .35)] = False; band[top + int(h * .65):] = False
            by, bx = np.where(band)
            front = bx.min(); hy = float(np.median(by[bx <= front + 3]))
            vh = spec['visibleHeight']
            torso.append([round(float(front + 5 + vh * .12), 2), round(hy - vh * .15, 2)])
        if 12 <= i < 18:
            band = a.copy(); band[:top + int(h * .2)] = False; band[top + int(h * .6):] = False
            by, bx = np.where(band)
            front = bx.min()
            near = by[bx <= front + 3]
            grip.append([round(float(front + 2), 2), round(float(np.median(near)), 2)])
    out['bodies'][body] = {'visibleHeight': spec['visibleHeight'], 'torso': torso, 'grip': grip}
    print(body, 'idle torso', torso[0], 'punch grips', grip)

js = ('/* Generated by tools/make-recruit-weapon-points.py from dist/assets/recruit-art-v2.\n'
      '   Where cw-weapon-art.js holds the sword and crossbow on the new recruit sheets. */\n'
      'globalThis.CWRecruitWeaponPoints=' + json.dumps(out, separators=(',', ':')) + ';\n')
open(os.path.join(DIST, 'cw-recruit-weapon-points.js'), 'w').write(js)
